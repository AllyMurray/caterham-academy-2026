"""Build the offline search index from the site's actual headings and content.

Run after changing HTML: python3 scripts/build-search-index.py
"""

import json
import re
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


class SearchPage(HTMLParser):
    def __init__(self, filename):
        super().__init__(convert_charrefs=True)
        self.filename = filename
        self.in_main = False
        self.heading = None
        self.page_title = ""
        self.current = None
        self.entries = []
        self.skip = 0

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "main":
            self.in_main = True
        if tag in ("script", "style", "nav"):
            self.skip += 1
        if tag == "h1":
            self.heading = {"tag": tag, "text": [], "id": None}
        if self.in_main and tag in ("h2", "h3") and attrs.get("id"):
            self.heading = {"tag": tag, "text": [], "id": attrs["id"]}

    def handle_endtag(self, tag):
        if tag in ("script", "style", "nav"):
            self.skip = max(0, self.skip - 1)
        if self.heading and tag == self.heading["tag"]:
            title = " ".join(" ".join(self.heading["text"]).split())
            if tag == "h1":
                self.page_title = title
            else:
                self.current = {
                    "title": title,
                    "section": self.page_title,
                    "url": self.filename + "#" + self.heading["id"],
                    "text": [],
                }
                self.entries.append(self.current)
            self.heading = None
        if tag == "main":
            self.in_main = False
        if self.in_main and self.current and tag in ("p", "li", "td", "dd"):
            self.current["text"].append(" ")

    def handle_data(self, data):
        if self.skip:
            return
        if self.heading:
            self.heading["text"].append(data)
        elif self.in_main and self.current:
            self.current["text"].append(data)


entries = []
for path in sorted(ROOT.glob("*.html")):
    if path.name == "search.html":
        continue
    parser = SearchPage(path.name)
    parser.feed(path.read_text())
    for entry in parser.entries:
        text = re.sub(r"\s+", " ", " ".join(entry.pop("text"))).strip()
        entry["summary"] = text[:220].rsplit(" ", 1)[0] + "…" if len(text) > 220 else text
        entry["keywords"] = text
        entries.append(entry)

output = "// Generated by scripts/build-search-index.py; do not edit by hand.\n"
output += "window.SITE_SEARCH_INDEX = " + json.dumps(entries, ensure_ascii=False, separators=(",", ":")) + ";\n"
(ROOT / "search-index.js").write_text(output)
print(f"Indexed {len(entries)} sections from 15 pages.")
